@contextmanager
def _sesion(engine, schema):
    with Session(engine, autoflush=False) as db:
        db.execute(text(f'SET LOCAL search_path TO "{schema}"'))
        yield db


def _cliente(engine, schema):
    app = FastAPI()
    app.include_router(router)

    def db_prueba():
        with _sesion(engine, schema) as db:
            yield db

    app.dependency_overrides[get_db] = db_prueba
    app.dependency_overrides[get_tenant_claims] = lambda: {"tenant_id": schema}
    app.dependency_overrides[obtener_administrador_actual] = lambda: SimpleNamespace(id=7)
    return TestClient(app)


def test_postgres_rutas_y_tenants_aislados(pg_cu27):
    engine, (empresa_a, empresa_b) = pg_cu27
    with _cliente(engine, empresa_a) as a, _cliente(engine, empresa_b) as b:
        assert "post" in a.get("/openapi.json").json()["paths"]["/inventario-proveedores/movimientos"]
        crear = a.post("/inventario-proveedores/movimientos", json={
            "lote_id": 1, "tipo": "STOCK_INICIAL", "cantidad": 17,
        })
        assert crear.status_code == 201, crear.text
        assert crear.json()["stock_anterior"] == 0
        assert crear.json()["stock_posterior"] == 17

        assert a.get("/inventario-proveedores/existencias/1").json()["stock_actual"] == 17
        assert b.get("/inventario-proveedores/existencias/1").json()["stock_actual"] == 0
        assert len(a.get("/inventario-proveedores/movimientos").json()) == 1
        assert b.get("/inventario-proveedores/movimientos").json() == []


def test_postgres_restricciones_y_reservas(pg_cu27):
    engine, (empresa_a, _) = pg_cu27
    with _cliente(engine, empresa_a) as cli:
        assert cli.post("/inventario-proveedores/movimientos", json={
            "lote_id": 1, "tipo": "STOCK_INICIAL", "cantidad": 10,
        }).status_code == 201
        with _sesion(engine, empresa_a) as db:
            db.execute(text("UPDATE inventario SET stock_reservado=8 WHERE lote_id=1"))
            db.commit()
        assert cli.post("/inventario-proveedores/movimientos", json={
            "lote_id": 1, "tipo": "SALIDA_USO", "cantidad": 3,
        }).status_code == 409
        assert cli.get("/inventario-proveedores/existencias/1").json()["stock_actual"] == 10
        assert len(cli.get("/inventario-proveedores/movimientos").json()) == 1

    # Verifica que los CHECK reales de PostgreSQL rechacen saldos incoherentes.
    with _sesion(engine, empresa_a) as db:
        id_inventario = db.scalar(text("SELECT id FROM inventario WHERE lote_id=1"))
        with pytest.raises(IntegrityError):
            db.execute(text(
                "INSERT INTO movimiento_inventario("
                "inventario_id, usuario_id, tipo, cantidad, stock_anterior, stock_posterior)"
                " VALUES (:inv,7,'SALIDA_USO',3,10,10)"
            ), {"inv": id_inventario})
            db.flush()
        db.rollback()


def test_postgres_movimiento_automatico_reintento_y_rollback(pg_cu27):
    engine, (empresa_a, _) = pg_cu27
    with _sesion(engine, empresa_a) as db:
        r = movimientos.registrar_movimiento_automatico(
            db, lote_id=1, tipo="ENTRADA_COMPRA", cantidad=4, usuario_id=7,
            referencia_tipo="DETALLE_COMPRA", referencia_id=501,
        )
        assert r.stock_posterior == 4
        db.rollback()
    with _sesion(engine, empresa_a) as db:
        assert movimientos.consultar_existencia(db, 1).stock_actual == 0
        r = movimientos.registrar_movimiento_automatico(
            db, lote_id=1, tipo="ENTRADA_COMPRA", cantidad=4, usuario_id=7,
            referencia_tipo="DETALLE_COMPRA", referencia_id=501,
        )
        assert r.stock_posterior == 4
        db.commit()
    with _sesion(engine, empresa_a) as db:
        with pytest.raises(HTTPException) as ex:
            movimientos.registrar_movimiento_automatico(
                db, lote_id=1, tipo="ENTRADA_COMPRA", cantidad=4, usuario_id=7,
                referencia_tipo="DETALLE_COMPRA", referencia_id=501,
            )
        assert ex.value.status_code == 409
        db.rollback()
    with _sesion(engine, empresa_a) as db:
        assert movimientos.consultar_existencia(db, 1).stock_actual == 4


