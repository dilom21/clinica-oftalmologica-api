def test_cu27_jwt_manipulado_cruzado_o_legacy_denegado(api_cu27_jwt_real):
    import jwt
    from datetime import datetime, timedelta, timezone
    from app.core.config import JWT_ALGORITHM, JWT_SECRET_KEY
    from app.core.security import crear_access_token

    client, token, mapping, _, _ = api_cu27_jwt_real
    ruta = "/inventario-proveedores/existencias/1"
    assert client.get(ruta).status_code in (401, 403)
    assert client.get(ruta, headers=_headers(crear_access_token(7, 1))).status_code == 401

    cruzado = token("CLINICA-A", tenant_id=mapping["CLINICA-B"]["tenant_id"])
    assert client.get(ruta, headers=_headers(cruzado)).status_code == 401
    falsa_empresa = token("CLINICA-A", empresa_id=mapping["CLINICA-B"]["empresa_id"])
    assert client.get(ruta, headers=_headers(falsa_empresa)).status_code == 401

    firmado_mal = jwt.encode(
        {"sub": "7", "rol_id": 1, "tenant_id": 1001,
         "empresa_id": 101, "empresa_codigo": "CLINICA-A",
         "token_type": "tenant", "exp": datetime.now(timezone.utc) + timedelta(minutes=5)},
        "clave-falsa-solo-pruebas", algorithm=JWT_ALGORITHM,
    )
    assert client.get(ruta, headers=_headers(firmado_mal)).status_code == 401
    vencido = jwt.encode(
        {"sub": "7", "rol_id": 1, "tenant_id": 1001,
         "empresa_id": 101, "empresa_codigo": "CLINICA-A",
         "token_type": "tenant", "exp": datetime.now(timezone.utc) - timedelta(seconds=10)},
        JWT_SECRET_KEY, algorithm=JWT_ALGORITHM,
    )
    assert client.get(ruta, headers=_headers(vencido)).status_code == 401


def test_cu27_jwt_suspension_usuario_rol_denegados(api_cu27_jwt_real):
    client, token, mapping, estados, engine = api_cu27_jwt_real
    url = "/inventario-proveedores/movimientos"
    a = _headers(token("CLINICA-A"))

    estados["CLINICA-A"] = "SUSPENDIDA"
    assert client.get(url, headers=a).status_code == 503
    estados["CLINICA-A"] = "ACTIVA"

    # Un token válido con rol no coincidente con BD se invalida.
    assert client.get(url, headers=_headers(token("CLINICA-A", rol=2))).status_code == 401

    with _sesion(engine, mapping["CLINICA-A"]["schema"]) as db:
        db.execute(text("UPDATE usuario SET rol_id=2 WHERE id=7"))
        db.commit()
    # Rol vigente, pero no administrador: acceso prohibido.
    assert client.get(url, headers=_headers(token("CLINICA-A", rol=2))).status_code == 403

    with _sesion(engine, mapping["CLINICA-A"]["schema"]) as db:
        db.execute(text("UPDATE usuario SET estado=FALSE WHERE id=7"))
        db.commit()
    assert client.get(url, headers=_headers(token("CLINICA-A", rol=2))).status_code == 401
