def _headers(jwt_token):
    return {"Authorization": f"Bearer {jwt_token}"}


def test_cu27_jwt_valido_resuelve_clinica_y_aisla_datos(api_cu27_jwt_real):
    client, token, mapping, _, engine = api_cu27_jwt_real
    a = _headers(token("CLINICA-A"))
    b = _headers(token("CLINICA-B"))
    nuevo = {"lote_id": 1, "tipo": "STOCK_INICIAL", "cantidad": 23}

    assert client.post("/inventario-proveedores/movimientos", headers=a, json=nuevo).status_code == 201
    assert client.get("/inventario-proveedores/existencias/1", headers=a).json()["stock_actual"] == 23
    assert client.get("/inventario-proveedores/existencias/1", headers=b).json()["stock_actual"] == 0
    assert len(client.get("/inventario-proveedores/movimientos", headers=a).json()) == 1
    assert client.get("/inventario-proveedores/movimientos", headers=b).json() == []

