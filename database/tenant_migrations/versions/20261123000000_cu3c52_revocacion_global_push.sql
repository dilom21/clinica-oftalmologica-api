-- Fase 3C.5.2: outbox durable de revocacion global de huellas FCM.
--
-- Migracion ADITIVA sobre el esquema v8 de 3C.5. No recrea tablas, no modifica
-- datos y no toca las migraciones historicas 20261121000000 ni 20261122000000.
--
-- Cambios:
--   * public.dispositivo_push_revocacion: solicitud durable e idempotente que
--     crea el worker FCM cuando el proveedor informa inequivocamente que un
--     token dejo de ser valido (UNREGISTERED, INVALID_REGISTRATION,
--     SENDER_ID_MISMATCH). Solo guarda la huella SHA-256 calculada en backend,
--     nunca el token original.
--   * la unicidad (dispositivo_id, token_fingerprint) impide duplicados; si el
--     dispositivo rota su token, la nueva huella genera una solicitud nueva.
--   * indice de cola (estado, proximo_intento) e indice parcial de leases.
--
-- Transaccion controlada por tenant_migrator.py. No incluir BEGIN/COMMIT.
-- RLS permanece DESACTIVADO por la instruccion vigente del propietario.

SET LOCAL lock_timeout = '5s';
SET LOCAL statement_timeout = '60s';

DO $preflight$
DECLARE
    v_lease boolean;
    v_estado text;
BEGIN
    IF to_regclass('public.dispositivo_push') IS NULL THEN
        RAISE EXCEPTION
            'Fase 3C.5.2: falta public.dispositivo_push de 3C.2';
    END IF;
    IF to_regclass('public.usuario') IS NULL THEN
        RAISE EXCEPTION
            'Fase 3C.5.2: falta public.usuario';
    END IF;
    IF to_regclass('public.notificacion_entrega') IS NULL THEN
        RAISE EXCEPTION
            'Fase 3C.5.2: falta el outbox de 3C.2 (public.notificacion_entrega)';
    END IF;

    -- La migracion 3C.5 debe estar aplicada (v8): lease y estado OMITIDO.
    SELECT EXISTS (
        SELECT 1 FROM pg_attribute
         WHERE attrelid = 'public.notificacion_entrega'::regclass
           AND attname = 'lease_token' AND attnum > 0 AND NOT attisdropped
    ) INTO v_lease;
    IF NOT v_lease THEN
        RAISE EXCEPTION
            'Fase 3C.5.2: requiere 3C.5 aplicada (falta notificacion_entrega.lease_token)';
    END IF;

    SELECT pg_get_constraintdef(oid) INTO v_estado
      FROM pg_constraint
     WHERE conname = 'ck_notificacion_entrega_estado'
       AND conrelid = 'public.notificacion_entrega'::regclass;
    IF v_estado IS NULL OR v_estado NOT LIKE '%OMITIDO%' THEN
        RAISE EXCEPTION
            'Fase 3C.5.2: requiere 3C.5 aplicada (falta el estado OMITIDO)';
    END IF;

    IF to_regclass('public.dispositivo_push_revocacion') IS NOT NULL THEN
        RAISE EXCEPTION
            'Fase 3C.5.2: instalacion parcial: la tabla ya existe';
    END IF;
END
$preflight$;

CREATE TABLE public.dispositivo_push_revocacion (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dispositivo_id BIGINT NOT NULL
        REFERENCES public.dispositivo_push(id) ON DELETE RESTRICT,
    -- Identificador local del usuario del tenant; siempre se interpreta junto
    -- con la base tenant, porque los IDs de usuario no son globalmente unicos.
    usuario_id BIGINT NOT NULL
        REFERENCES public.usuario(id) ON DELETE RESTRICT,
    -- SHA-256 hexadecimal en minusculas de 64 caracteres; nunca el token real.
    token_fingerprint VARCHAR(64) NOT NULL,
    estado VARCHAR(20) NOT NULL DEFAULT 'PENDIENTE',
    intentos SMALLINT NOT NULL DEFAULT 0,
    proximo_intento TIMESTAMPTZ,
    bloqueado_hasta TIMESTAMPTZ,
    lease_token VARCHAR(64),
    codigo_ultimo_error VARCHAR(100),
    fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT now(),
    fecha_actualizacion TIMESTAMPTZ NOT NULL DEFAULT now(),
    fecha_procesado TIMESTAMPTZ,
    CONSTRAINT uq_dispositivo_push_revocacion_dispositivo_huella
        UNIQUE (dispositivo_id, token_fingerprint),
    CONSTRAINT ck_dispositivo_push_revocacion_huella CHECK (
        token_fingerprint ~ '^[0-9a-f]{64}$'
    ),
    CONSTRAINT ck_dispositivo_push_revocacion_estado CHECK (
        estado IN ('PENDIENTE', 'PROCESANDO', 'COMPLETADA',
                   'NO_ENCONTRADO', 'RECHAZADA', 'FALLIDA')
    ),
    CONSTRAINT ck_dispositivo_push_revocacion_intentos CHECK (intentos >= 0)
);

CREATE INDEX ix_dispositivo_push_revocacion_cola
    ON public.dispositivo_push_revocacion (estado, proximo_intento);
CREATE INDEX ix_dispositivo_push_revocacion_lease
    ON public.dispositivo_push_revocacion (bloqueado_hasta)
    WHERE estado = 'PROCESANDO';
CREATE INDEX ix_dispositivo_push_revocacion_usuario
    ON public.dispositivo_push_revocacion (usuario_id, estado);

COMMENT ON TABLE public.dispositivo_push_revocacion IS
    'Fase 3C.5.2: outbox tenant de solicitudes de revocacion global; sin token original.';
COMMENT ON COLUMN public.dispositivo_push_revocacion.token_fingerprint IS
    'SHA-256 hex del token FCM invalidado. Prohibido exponerla en HTTP o logs.';
COMMENT ON COLUMN public.dispositivo_push_revocacion.lease_token IS
    'Fase 3C.5.2: fencing token del procesador; nulo cuando no esta reclamada.';
REVOKE ALL PRIVILEGES ON TABLE public.dispositivo_push_revocacion FROM PUBLIC;

DO $security$
DECLARE
    v_role text;
    v_seq text;
BEGIN
    FOR v_role IN SELECT rolname FROM pg_roles
                  WHERE rolname IN ('anon', 'authenticated')
    LOOP
        EXECUTE format(
            'REVOKE ALL PRIVILEGES ON TABLE public.dispositivo_push_revocacion FROM %I',
            v_role
        );
    END LOOP;

    v_seq := pg_get_serial_sequence(
        'public.dispositivo_push_revocacion', 'id'
    );

    IF v_seq IS NULL THEN
        RAISE EXCEPTION
            'Fase 3C.5.2: no se encontro la secuencia de identidad';
    END IF;

    EXECUTE format(
        'REVOKE ALL PRIVILEGES ON SEQUENCE %s FROM PUBLIC', v_seq
    );

    FOR v_role IN SELECT rolname FROM pg_roles
                  WHERE rolname IN ('anon', 'authenticated')
    LOOP
        EXECUTE format(
            'REVOKE ALL PRIVILEGES ON SEQUENCE %s FROM %I',
            v_seq, v_role
        );
    END LOOP;
END
$security$;

DO $postflight$
DECLARE
    v_estado text;
    v_huella text;
    v_role text;
    v_seq text;
BEGIN
    IF to_regclass('public.dispositivo_push_revocacion') IS NULL THEN
        RAISE EXCEPTION
            'Fase 3C.5.2: no se creo dispositivo_push_revocacion';
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
         WHERE conname = 'uq_dispositivo_push_revocacion_dispositivo_huella'
           AND conrelid = 'public.dispositivo_push_revocacion'::regclass
    ) THEN
        RAISE EXCEPTION
            'Fase 3C.5.2: falta la clave de idempotencia dispositivo/huella';
    END IF;

    SELECT pg_get_constraintdef(oid) INTO v_estado
      FROM pg_constraint
     WHERE conname = 'ck_dispositivo_push_revocacion_estado';
    IF v_estado IS NULL
       OR v_estado NOT LIKE '%COMPLETADA%'
       OR v_estado NOT LIKE '%RECHAZADA%'
       OR v_estado NOT LIKE '%FALLIDA%' THEN
        RAISE EXCEPTION
            'Fase 3C.5.2: restriccion de estado incompleta';
    END IF;

    SELECT pg_get_constraintdef(oid) INTO v_huella
      FROM pg_constraint
     WHERE conname = 'ck_dispositivo_push_revocacion_huella';
    IF v_huella IS NULL
       OR v_huella NOT LIKE '%^[0-9a-f]{64}$%' THEN
        RAISE EXCEPTION
            'Fase 3C.5.2: la huella no valida SHA-256 hexadecimal';
    END IF;

    -- El token original jamas debe aparecer en este outbox.
    IF EXISTS (
        SELECT 1 FROM information_schema.columns
         WHERE table_schema = 'public'
           AND table_name = 'dispositivo_push_revocacion'
           AND column_name IN ('token_fcm', 'token', 'fcm_token')
    ) THEN
        RAISE EXCEPTION
            'Fase 3C.5.2: el outbox no debe guardar el token original';
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_indexes
         WHERE schemaname = 'public'
           AND indexname = 'ix_dispositivo_push_revocacion_cola'
    ) OR NOT EXISTS (
        SELECT 1 FROM pg_indexes
         WHERE schemaname = 'public'
           AND indexname = 'ix_dispositivo_push_revocacion_lease'
           AND indexdef LIKE '%WHERE%'
    ) OR NOT EXISTS (
        SELECT 1 FROM pg_indexes
         WHERE schemaname = 'public'
           AND indexname = 'ix_dispositivo_push_revocacion_usuario'
    ) THEN
        RAISE EXCEPTION
            'Fase 3C.5.2: faltan indices del outbox de revocaciones';
    END IF;
    -- PUBLIC no debe conservar privilegios en la tabla.
    IF EXISTS (
        SELECT 1
          FROM pg_class c
          CROSS JOIN LATERAL aclexplode(
              COALESCE(c.relacl, acldefault('r', c.relowner))
          ) a
         WHERE c.oid = 'public.dispositivo_push_revocacion'::regclass
           AND a.grantee = 0
    ) THEN
        RAISE EXCEPTION
            'Fase 3C.5.2: PUBLIC conserva privilegios en la tabla de revocaciones';
    END IF;

    FOR v_role IN SELECT rolname FROM pg_roles
                  WHERE rolname IN ('anon', 'authenticated')
    LOOP
        IF has_table_privilege(v_role, 'public.dispositivo_push_revocacion', 'SELECT')
           OR has_table_privilege(v_role, 'public.dispositivo_push_revocacion', 'INSERT')
           OR has_table_privilege(v_role, 'public.dispositivo_push_revocacion', 'UPDATE')
           OR has_table_privilege(v_role, 'public.dispositivo_push_revocacion', 'DELETE')
           OR has_table_privilege(v_role, 'public.dispositivo_push_revocacion', 'TRUNCATE')
           OR has_table_privilege(v_role, 'public.dispositivo_push_revocacion', 'REFERENCES')
           OR has_table_privilege(v_role, 'public.dispositivo_push_revocacion', 'TRIGGER')
        THEN
            RAISE EXCEPTION
                'Fase 3C.5.2: % conserva privilegios en la tabla de revocaciones',
                v_role;
        END IF;
    END LOOP;

    v_seq := pg_get_serial_sequence(
        'public.dispositivo_push_revocacion', 'id'
    );

    IF v_seq IS NULL THEN
        RAISE EXCEPTION
            'Fase 3C.5.2: falta la secuencia de identidad';
    END IF;

    -- PUBLIC tampoco debe acceder a la secuencia.
    IF EXISTS (
        SELECT 1
          FROM pg_class c
          CROSS JOIN LATERAL aclexplode(
              COALESCE(c.relacl, acldefault('S', c.relowner))
          ) a
         WHERE c.oid = v_seq::regclass
           AND a.grantee = 0
    ) THEN
        RAISE EXCEPTION
            'Fase 3C.5.2: PUBLIC conserva privilegios en la secuencia';
    END IF;

    FOR v_role IN SELECT rolname FROM pg_roles
                  WHERE rolname IN ('anon', 'authenticated')
    LOOP
        IF has_sequence_privilege(v_role, v_seq, 'USAGE')
           OR has_sequence_privilege(v_role, v_seq, 'SELECT')
           OR has_sequence_privilege(v_role, v_seq, 'UPDATE')
        THEN
            RAISE EXCEPTION
                'Fase 3C.5.2: % conserva privilegios en la secuencia',
                v_role;
        END IF;
    END LOOP;
END
$postflight$;
