-- CU36 I-2: cuarentena central de refunds Stripe sin metadata de tenant.
--
-- Un refund creado desde el dashboard de Stripe no lleva metadata propia. El
-- router consulta el PaymentIntent en Stripe (metadata confiable generada por
-- el servidor) y enruta al tenant. Cuando el PaymentIntent tampoco identifica
-- un tenant, el evento NUNCA se envia a la base legacy: se guarda aqui, en el
-- Control Plane, y solo un SUPERADMIN puede atribuirlo manualmente a una
-- empresa concreta.
--
-- Additive migration over 001..007. No habilita RLS en ningun tenant.
BEGIN;

CREATE TABLE IF NOT EXISTS saas_control.stripe_webhook_huerfano (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stripe_event_id VARCHAR(255) NOT NULL,
    event_type VARCHAR(100) NOT NULL,
    refund_id VARCHAR(255) NOT NULL,
    payment_intent_id VARCHAR(255),
    amount BIGINT NOT NULL,
    currency VARCHAR(3) NOT NULL,
    status VARCHAR(30) NOT NULL,
    payload TEXT NOT NULL,
    estado VARCHAR(20) NOT NULL DEFAULT 'PENDIENTE',
    empresa_id BIGINT REFERENCES saas_control.empresa(id) ON DELETE RESTRICT,
    tenant_database_id BIGINT REFERENCES saas_control.tenant_database(id) ON DELETE RESTRICT,
    -- Referencia logica al ajuste del tenant; no puede ser FK entre bases.
    ajuste_id BIGINT,
    motivo TEXT,
    atribuido_por BIGINT REFERENCES saas_control.saas_usuario(id) ON DELETE SET NULL,
    creado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
    actualizado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_stripe_webhook_huerfano_central_evento UNIQUE (stripe_event_id),
    CONSTRAINT ck_stripe_webhook_huerfano_central_amount CHECK (amount > 0),
    CONSTRAINT ck_stripe_webhook_huerfano_central_moneda CHECK (
        length(currency) = 3 AND currency = upper(currency)
    ),
    CONSTRAINT ck_stripe_webhook_huerfano_central_estado CHECK (
        estado IN ('PENDIENTE', 'ATRIBUIDO', 'DESCARTADO')
    ),
    -- Un evento atribuido debe identificar empresa y base; uno pendiente no.
    CONSTRAINT ck_stripe_webhook_huerfano_central_atribucion CHECK (
        estado <> 'ATRIBUIDO'
        OR (empresa_id IS NOT NULL AND tenant_database_id IS NOT NULL)
    )
);

CREATE INDEX IF NOT EXISTS idx_stripe_huerfano_central_refund
    ON saas_control.stripe_webhook_huerfano (refund_id, estado);
CREATE INDEX IF NOT EXISTS idx_stripe_huerfano_central_pi
    ON saas_control.stripe_webhook_huerfano (payment_intent_id);
CREATE INDEX IF NOT EXISTS idx_stripe_huerfano_central_pendientes
    ON saas_control.stripe_webhook_huerfano (creado_en)
    WHERE estado = 'PENDIENTE';

COMMENT ON TABLE saas_control.stripe_webhook_huerfano IS
    'CU36 I-2: refund Stripe verificado sin tenant resoluble; cuarentena central y atribucion manual.';
COMMENT ON COLUMN saas_control.stripe_webhook_huerfano.payload IS
    'Evento Stripe original serializado; evidencia de auditoria.';
COMMENT ON COLUMN saas_control.stripe_webhook_huerfano.ajuste_id IS
    'Referencia logica al pago_ajuste del tenant; sin FK entre bases.';

REVOKE ALL PRIVILEGES ON TABLE saas_control.stripe_webhook_huerfano FROM PUBLIC;
REVOKE ALL PRIVILEGES ON SEQUENCE saas_control.stripe_webhook_huerfano_id_seq FROM PUBLIC;

DO $security$
DECLARE
    v_role text;
BEGIN
    FOR v_role IN SELECT rolname FROM pg_roles
                  WHERE rolname IN ('anon', 'authenticated')
    LOOP
        EXECUTE format(
            'REVOKE ALL PRIVILEGES ON TABLE saas_control.stripe_webhook_huerfano FROM %I',
            v_role
        );
        EXECUTE format(
            'REVOKE ALL PRIVILEGES ON SEQUENCE saas_control.stripe_webhook_huerfano_id_seq FROM %I',
            v_role
        );
    END LOOP;
END
$security$;

COMMIT;
