-- Fase 3C.2: registro global minimo de propiedad de tokens FCM.
--
-- El Control Plane guarda UNICAMENTE una huella SHA-256 determinista del token.
-- El token en claro sigue viviendo solo en public.dispositivo_push de cada base
-- tenant, porque es alli donde el futuro worker lo necesita para enviar.
--
-- Este registro permite detectar que un mismo token intenta quedar activo en
-- dos empresas distintas. No contiene correo, nombre, paciente, datos clinicos
-- ni contenido de notificaciones.
--
-- La reasignacion de un token entre empresas NO es atomica entre dos bases
-- PostgreSQL: el futuro servicio debera implementar claim/reserva con
-- confirmacion o compensacion (saga). Esta fase solo prepara la persistencia.
--
-- Migracion aditiva sobre 001..008. No habilita RLS en ningun tenant.
BEGIN;

CREATE TABLE IF NOT EXISTS saas_control.dispositivo_push_registry (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- Hash hexadecimal en minusculas de 64 caracteres; nunca el token real.
    token_fingerprint VARCHAR(64) NOT NULL,
    tenant_database_id BIGINT NOT NULL
        REFERENCES saas_control.tenant_database(id) ON DELETE RESTRICT,
    -- Identificador local del usuario del tenant. Solo tiene sentido junto a
    -- tenant_database_id: los IDs de usuario no son globalmente unicos.
    usuario_id BIGINT NOT NULL,
    estado VARCHAR(20) NOT NULL DEFAULT 'ACTIVO',
    huella_version SMALLINT NOT NULL DEFAULT 1,
    fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT now(),
    fecha_actualizacion TIMESTAMPTZ NOT NULL DEFAULT now(),
    fecha_revocacion TIMESTAMPTZ,
    CONSTRAINT uq_dispositivo_push_registry_huella UNIQUE (token_fingerprint),
    CONSTRAINT ck_dispositivo_push_registry_huella CHECK (
        length(token_fingerprint) = 64
        AND token_fingerprint = lower(token_fingerprint)
    ),
    CONSTRAINT ck_dispositivo_push_registry_estado CHECK (
        estado IN ('PENDIENTE', 'ACTIVO', 'REVOCADO')
    ),
    CONSTRAINT ck_dispositivo_push_registry_version CHECK (huella_version >= 1),
    CONSTRAINT ck_dispositivo_push_registry_revocacion CHECK (
        (estado = 'REVOCADO' AND fecha_revocacion IS NOT NULL)
        OR (estado <> 'REVOCADO' AND fecha_revocacion IS NULL)
    ),
    CONSTRAINT ck_dispositivo_push_registry_usuario CHECK (usuario_id > 0)
);

CREATE INDEX IF NOT EXISTS ix_dispositivo_push_registry_tenant_usuario
    ON saas_control.dispositivo_push_registry (tenant_database_id, usuario_id);
CREATE INDEX IF NOT EXISTS ix_dispositivo_push_registry_estado
    ON saas_control.dispositivo_push_registry (estado, fecha_actualizacion);

COMMENT ON TABLE saas_control.dispositivo_push_registry IS
    'Fase 3C.2: propiedad global de huellas FCM; nunca almacena el token original.';
COMMENT ON COLUMN saas_control.dispositivo_push_registry.token_fingerprint IS
    'SHA-256 hex del token FCM. Prohibido exponerla en HTTP o logs.';
COMMENT ON COLUMN saas_control.dispositivo_push_registry.usuario_id IS
    'ID local del usuario del tenant; siempre interpretado con tenant_database_id.';

REVOKE ALL PRIVILEGES ON TABLE saas_control.dispositivo_push_registry FROM PUBLIC;
REVOKE ALL PRIVILEGES ON SEQUENCE
    saas_control.dispositivo_push_registry_id_seq FROM PUBLIC;

DO $security$
DECLARE
    v_role text;
BEGIN
    FOR v_role IN SELECT rolname FROM pg_roles
                  WHERE rolname IN ('anon', 'authenticated')
    LOOP
        EXECUTE format(
            'REVOKE ALL PRIVILEGES ON TABLE saas_control.dispositivo_push_registry FROM %I',
            v_role
        );
        EXECUTE format(
            'REVOKE ALL PRIVILEGES ON SEQUENCE saas_control.dispositivo_push_registry_id_seq FROM %I',
            v_role
        );
    END LOOP;
END
$security$;

DO $postflight$
DECLARE
    v_role text;
BEGIN
    IF to_regclass('saas_control.dispositivo_push_registry') IS NULL THEN
        RAISE EXCEPTION 'Fase 3C.2: falta saas_control.dispositivo_push_registry';
    END IF;
    -- El Control Plane nunca debe contener el token en claro.
    IF EXISTS (
        SELECT 1 FROM information_schema.columns
         WHERE table_schema='saas_control'
           AND table_name='dispositivo_push_registry'
           AND column_name IN ('token_fcm', 'token', 'fcm_token')
    ) THEN
        RAISE EXCEPTION 'Fase 3C.2: el registro global no debe guardar el token';
    END IF;
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
         WHERE conname='uq_dispositivo_push_registry_huella'
    ) THEN
        RAISE EXCEPTION 'Fase 3C.2: falta unicidad global de la huella';
    END IF;
    FOR v_role IN SELECT rolname FROM pg_roles
                  WHERE rolname IN ('anon','authenticated')
    LOOP
        IF has_table_privilege(
            v_role, 'saas_control.dispositivo_push_registry', 'SELECT'
        ) OR has_table_privilege(
            v_role, 'saas_control.dispositivo_push_registry', 'INSERT'
        ) OR has_table_privilege(
            v_role, 'saas_control.dispositivo_push_registry', 'UPDATE'
        ) OR has_table_privilege(
            v_role, 'saas_control.dispositivo_push_registry', 'DELETE'
        ) THEN
            RAISE EXCEPTION 'Fase 3C.2: % conserva privilegios en el registro',
                v_role;
        END IF;
    END LOOP;
END
$postflight$;

COMMIT;
